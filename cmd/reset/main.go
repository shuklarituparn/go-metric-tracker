package main

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/printer"
	"go/token"
	"log"
	"os"
	"path/filepath"
	"strconv"
	"strings"
)

type StructInfo struct {
	Name   string
	Fields []*ast.Field
}

type PackageInfo struct {
	Name string
	Path string

	Structs []StructInfo

	Imports map[string]string

	NeededAliases map[string]bool
}

func main() {
	rootDir := "."
	if len(os.Args) > 1 {
		rootDir = os.Args[1]
	}

	packages, err := scanPackages(rootDir)
	if err != nil {
		log.Fatalf("Failed to scan packages: %v", err)
	}

	for _, pkg := range packages {
		if len(pkg.Structs) == 0 {
			continue
		}
		if err := generateResetFile(pkg); err != nil {
			log.Printf("Failed to generate reset file for package %s: %v", pkg.Name, err)
		} else {
			log.Printf("Generated reset.gen.go for package %s with %d struct(s)", pkg.Name, len(pkg.Structs))
		}
	}
}

func scanPackages(rootDir string) ([]PackageInfo, error) {
	var packages []PackageInfo

	err := filepath.Walk(rootDir, func(path string, info os.FileInfo, err error) error {
		if err != nil {
			return err
		}
		if !info.IsDir() {
			return nil
		}

		if path != rootDir && (strings.HasPrefix(info.Name(), ".") || info.Name() == "vendor") {
			return filepath.SkipDir
		}

		pkgInfo, err := scanPackage(path)
		if err != nil {
			return nil
		}

		if pkgInfo != nil && len(pkgInfo.Structs) > 0 {
			packages = append(packages, *pkgInfo)
		}
		return nil
	})

	return packages, err
}

func scanPackage(pkgPath string) (*PackageInfo, error) {
	fset := token.NewFileSet()
	pkgs, err := parser.ParseDir(fset, pkgPath, func(info os.FileInfo) bool {
		return !strings.HasSuffix(info.Name(), "_test.go") &&
			!strings.HasSuffix(info.Name(), ".gen.go")
	}, parser.ParseComments)
	if err != nil {
		return nil, err
	}
	if len(pkgs) == 0 {
		return nil, fmt.Errorf("no pkgs")
	}

	var pkgInfo *PackageInfo

	for pkgName, pkg := range pkgs {
		for _, file := range pkg.Files {
			if pkgInfo == nil {
				pkgInfo = &PackageInfo{
					Name:          pkgName,
					Path:          pkgPath,
					Structs:       nil,
					Imports:       map[string]string{},
					NeededAliases: map[string]bool{},
				}
			}

			collectImports(pkgInfo, file)

			structs := findResetableStructs(file)
			if len(structs) > 0 {
				pkgInfo.Structs = append(pkgInfo.Structs, structs...)
			}
		}
	}

	if pkgInfo == nil || len(pkgInfo.Structs) == 0 {
		return nil, nil
	}

	markNeededAliases(pkgInfo)

	return pkgInfo, nil
}

func collectImports(pkg *PackageInfo, file *ast.File) {
	for _, imp := range file.Imports {
		path, err := strconv.Unquote(imp.Path.Value)
		if err != nil {
			continue
		}

		alias := ""
		if imp.Name != nil {
			alias = imp.Name.Name 
		} else {
			parts := strings.Split(path, "/")
			alias = parts[len(parts)-1]
		}

		if _, exists := pkg.Imports[alias]; !exists {
			pkg.Imports[alias] = path
		}
	}
}

func findResetableStructs(file *ast.File) []StructInfo {
	var structs []StructInfo

	ast.Inspect(file, func(n ast.Node) bool {
		genDecl, ok := n.(*ast.GenDecl)
		if !ok || genDecl.Tok != token.TYPE {
			return true
		}
		if genDecl.Doc == nil {
			return true
		}

		hasResetComment := false
		for _, comment := range genDecl.Doc.List {
			if strings.Contains(comment.Text, "generate:reset") {
				hasResetComment = true
				break
			}
		}
		if !hasResetComment {
			return true
		}

		for _, spec := range genDecl.Specs {
			typeSpec, ok := spec.(*ast.TypeSpec)
			if !ok {
				continue
			}
			structType, ok := typeSpec.Type.(*ast.StructType)
			if !ok {
				continue
			}
			structs = append(structs, StructInfo{
				Name:   typeSpec.Name.Name,
				Fields: structType.Fields.List,
			})
		}

		return true
	})

	return structs
}

func markNeededAliases(pkg *PackageInfo) {
	for _, s := range pkg.Structs {
		for _, f := range s.Fields {
			if len(f.Names) == 0 {
				continue
			}
			inspectTypeForAliases(f.Type, pkg.NeededAliases)
		}
	}
}

func inspectTypeForAliases(expr ast.Expr, needed map[string]bool) {
	switch t := expr.(type) {
	case *ast.SelectorExpr:
		if x, ok := t.X.(*ast.Ident); ok {
			needed[x.Name] = true
		}
	case *ast.StarExpr:
		inspectTypeForAliases(t.X, needed)
	case *ast.ArrayType:
		inspectTypeForAliases(t.Elt, needed)
	case *ast.MapType:
		inspectTypeForAliases(t.Key, needed)
		inspectTypeForAliases(t.Value, needed)
	}
}

func generateResetFile(pkg PackageInfo) error {
	var buf bytes.Buffer

	fmt.Fprintf(&buf, "// Code generated by reset generator. DO NOT EDIT.\n\n")
	fmt.Fprintf(&buf, "package %s\n\n", pkg.Name)

	importLines := buildImportLines(pkg)
	if len(importLines) > 0 {
		buf.WriteString("import (\n")
		for _, line := range importLines {
			buf.WriteString("\t" + line + "\n")
		}
		buf.WriteString(")\n\n")
	}

	fset := token.NewFileSet()

	for _, structInfo := range pkg.Structs {
		generateResetMethod(&buf, fset, structInfo)
		buf.WriteString("\n")
	}

	formatted, err := format.Source(buf.Bytes())
	if err != nil {
		log.Printf("Warning: failed to format generated code: %v", err)
		formatted = buf.Bytes()
	}

	outputPath := filepath.Join(pkg.Path, "reset.gen.go")
	if err := os.WriteFile(outputPath, formatted, 0644); err != nil {
		return fmt.Errorf("failed to write file: %w", err)
	}
	return nil
}

func buildImportLines(pkg PackageInfo) []string {
	var lines []string
	for alias := range pkg.NeededAliases {
		if alias == "." || alias == "_" {
			continue
		}
		path, ok := pkg.Imports[alias]
		if !ok {
			log.Printf("Warning: selector alias %q used but import not found in package %s", alias, pkg.Name)
			continue
		}
		last := alias
		parts := strings.Split(path, "/")
		if len(parts) > 0 {
			last = parts[len(parts)-1]
		}
		if alias == last {
			lines = append(lines, fmt.Sprintf("%q", path))
		} else {
			lines = append(lines, fmt.Sprintf("%s %q", alias, path))
		}
	}
	return lines
}

func generateResetMethod(buf *bytes.Buffer, fset *token.FileSet, structInfo StructInfo) {
	fmt.Fprintf(buf, "func (r *%s) Reset() {\n", structInfo.Name)
	fmt.Fprintf(buf, "\tif r == nil {\n")
	fmt.Fprintf(buf, "\t\treturn\n")
	fmt.Fprintf(buf, "\t}\n\n")

	for _, field := range structInfo.Fields {
		if len(field.Names) == 0 {
			continue 
		}
		for _, name := range field.Names {
			generateFieldReset(buf, fset, name.Name, field.Type)
		}
	}

	fmt.Fprintf(buf, "}\n")
}

func generateFieldReset(buf *bytes.Buffer, fset *token.FileSet, fieldName string, fieldType ast.Expr) {
	switch t := fieldType.(type) {
	case *ast.Ident:
		if generateBasicTypeReset(buf, fieldName, t.Name) {
			return
		}
		fmt.Fprintf(buf, "\tif resetter, ok := interface{}(&r.%s).(interface{ Reset() }); ok {\n", fieldName)
		fmt.Fprintf(buf, "\t\tresetter.Reset()\n")
		fmt.Fprintf(buf, "\t} else {\n")
		fmt.Fprintf(buf, "\t\tvar zero %s\n", t.Name)
		fmt.Fprintf(buf, "\t\tr.%s = zero\n", fieldName)
		fmt.Fprintf(buf, "\t}\n")

	case *ast.StarExpr:
		generatePointerReset(buf, fset, fieldName, t.X)

	case *ast.ArrayType:
		if t.Len == nil {
			fmt.Fprintf(buf, "\tr.%s = r.%s[:0]\n", fieldName, fieldName)
		} else {
			fmt.Fprintf(buf, "\t// Array field r.%s: reset manually if needed\n", fieldName)
		}

	case *ast.MapType:
		fmt.Fprintf(buf, "\tclear(r.%s)\n", fieldName)

	case *ast.SelectorExpr:
		typeStr := exprString(fset, t)
		fmt.Fprintf(buf, "\tif resetter, ok := interface{}(&r.%s).(interface{ Reset() }); ok {\n", fieldName)
		fmt.Fprintf(buf, "\t\tresetter.Reset()\n")
		fmt.Fprintf(buf, "\t} else {\n")
		fmt.Fprintf(buf, "\t\tvar zero %s\n", typeStr)
		fmt.Fprintf(buf, "\t\tr.%s = zero\n", fieldName)
		fmt.Fprintf(buf, "\t}\n")

	default:
		fmt.Fprintf(buf, "\tif resetter, ok := interface{}(&r.%s).(interface{ Reset() }); ok {\n", fieldName)
		fmt.Fprintf(buf, "\t\tresetter.Reset()\n")
		fmt.Fprintf(buf, "\t}\n")
	}
}

func generateBasicTypeReset(buf *bytes.Buffer, fieldName, typeName string) bool {
	switch typeName {
	case "int", "int8", "int16", "int32", "int64",
		"uint", "uint8", "uint16", "uint32", "uint64", "uintptr",
		"float32", "float64", "complex64", "complex128":
		fmt.Fprintf(buf, "\tr.%s = 0\n", fieldName)
		return true
	case "string":
		fmt.Fprintf(buf, "\tr.%s = \"\"\n", fieldName)
		return true
	case "bool":
		fmt.Fprintf(buf, "\tr.%s = false\n", fieldName)
		return true
	case "byte", "rune":
		fmt.Fprintf(buf, "\tr.%s = 0\n", fieldName)
		return true
	default:
		return false
	}
}

func generatePointerReset(buf *bytes.Buffer, fset *token.FileSet, fieldName string, elemType ast.Expr) {
	fmt.Fprintf(buf, "\tif r.%s != nil {\n", fieldName)

	switch t := elemType.(type) {
	case *ast.Ident:
		switch t.Name {
		case "int", "int8", "int16", "int32", "int64",
			"uint", "uint8", "uint16", "uint32", "uint64", "uintptr",
			"float32", "float64", "complex64", "complex128",
			"byte", "rune":
			fmt.Fprintf(buf, "\t\t*r.%s = 0\n", fieldName)
		case "string":
			fmt.Fprintf(buf, "\t\t*r.%s = \"\"\n", fieldName)
		case "bool":
			fmt.Fprintf(buf, "\t\t*r.%s = false\n", fieldName)
		default:
			fmt.Fprintf(buf, "\t\tif resetter, ok := interface{}(r.%s).(interface{ Reset() }); ok {\n", fieldName)
			fmt.Fprintf(buf, "\t\t\tresetter.Reset()\n")
			fmt.Fprintf(buf, "\t\t} else {\n")
			fmt.Fprintf(buf, "\t\t\tvar zero %s\n", t.Name)
			fmt.Fprintf(buf, "\t\t\t*r.%s = zero\n", fieldName)
			fmt.Fprintf(buf, "\t\t}\n")
		}

	case *ast.SelectorExpr:
		typeStr := exprString(fset, t)
		fmt.Fprintf(buf, "\t\tif resetter, ok := interface{}(r.%s).(interface{ Reset() }); ok {\n", fieldName)
		fmt.Fprintf(buf, "\t\t\tresetter.Reset()\n")
		fmt.Fprintf(buf, "\t\t} else {\n")
		fmt.Fprintf(buf, "\t\t\tvar zero %s\n", typeStr)
		fmt.Fprintf(buf, "\t\t\t*r.%s = zero\n", fieldName)
		fmt.Fprintf(buf, "\t\t}\n")

	default:
		fmt.Fprintf(buf, "\t\tif resetter, ok := interface{}(r.%s).(interface{ Reset() }); ok {\n", fieldName)
		fmt.Fprintf(buf, "\t\t\tresetter.Reset()\n")
		fmt.Fprintf(buf, "\t\t}\n")
	}

	fmt.Fprintf(buf, "\t}\n")
}

func exprString(fset *token.FileSet, expr ast.Expr) string {
	var b bytes.Buffer
	_ = printer.Fprint(&b, fset, expr)
	return b.String()
}
